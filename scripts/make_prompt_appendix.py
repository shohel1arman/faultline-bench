"""The exact probe prompts, for the paper's appendix, generated from faultline/prompts.py.

  python scripts/make_prompt_appendix.py [--id fl_00002]

Writes results/tables/prompts.tex: every probe for one example record, turn by turn, as
the models received it. Needs no packages beyond standard LaTeX.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from faultline.prompts import PROMPT_VERSION, probe_turns, verbalize_turns  # noqa: E402
from faultline.schema import read_jsonl  # noqa: E402

PURPOSE = {
    "image_only": "Perception control: the question from the image alone, no description.",
    "text_only": "Reading control: the question from the description alone, no image.",
    "detect": "Detection: is the description accurate? (yes/no, then a reason)",
    "open": "Resolution, open-ended answer.",
    "mcq": "Resolution, multiple choice (scored from the next-token letter probabilities).",
    "mcq_focus": "Resolution with an instruction to rely on the image.",
    "attribute": "Attribution: a five-line error report.",
    "delay": "Control for verbalize: same turns, the assistant turn is a neutral reply.",
    "check_silent": "Control for verbalize: the check prompt, then a neutral reply.",
    "verbalize": "The model's own error report as the assistant turn, then the question.",
}
TITLE = {"image_only": "Image only", "text_only": "Text only", "detect": "Detect", "open": "Open",
         "mcq": "Multiple choice", "mcq_focus": "Focus", "attribute": "Attribute", "delay": "Delay",
         "check_silent": "Check (silent)", "verbalize": "Verbalize"}


def tex(s):
    """Escape plain text for LaTeX and keep line breaks."""
    rep = {"\\": "\\textbackslash{}", "&": "\\&", "%": "\\%", "$": "\\$", "#": "\\#", "_": "\\_",
           "{": "\\{", "}": "\\}", "~": "\\textasciitilde{}", "^": "\\textasciicircum{}"}
    out = "".join(rep.get(c, c) for c in s)
    # the prompt text is set in typewriter type, where " prints as a straight quote
    return "\\newline ".join(out.split("\n"))


def render(name, turns):
    lines = [f"\\paragraph{{{TITLE[name]}.}} {PURPOSE[name]}", "",
             "\\noindent\\fbox{\\parbox{\\dimexpr\\linewidth-2\\fboxsep-2\\fboxrule}{\\ttfamily\\footnotesize"]
    for k, t in enumerate(turns):
        who = "User" if t["role"] == "user" else "Assistant"
        img = "[image] " if t.get("image") else ""
        if k:
            lines.append("\\par\\smallskip")
        lines.append(f"\\textbf{{{who}:}} {img}{tex(t['text'])}")
    lines.append("}}")
    lines.append("")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="data/faultline_v0.jsonl")
    ap.add_argument("--id", default="fl_00002", help="example record (a core conflict)")
    ap.add_argument("--out", default="results/tables/prompts.tex")
    args = ap.parse_args()

    rec = next(r for r in read_jsonl(args.dataset) if r["id"] == args.id)
    probes = {name: turns for name, _, turns, _ in probe_turns(rec, image="IMAGE")}
    probes["verbalize"] = verbalize_turns(rec, "IMAGE", "<the model's own reply to the Attribute probe>")
    lines = [f"% generated by scripts/make_prompt_appendix.py from prompt version {PROMPT_VERSION}",
             f"Prompts for record {tex(rec['id'])} ({rec['conflict_type']}, {rec['severity']}): "
             f"the description says ``{tex(rec['edited_span'])}'' where the image shows "
             f"``{tex(rec['original_span'])}''. [image] marks where the photo is attached. "
             f"Multiple-choice probes are scored from the probabilities of the four option letters "
             f"as the next token; generated probes use greedy decoding.", ""]
    for name in ["image_only", "text_only", "detect", "open", "mcq", "mcq_focus", "attribute",
                 "delay", "check_silent", "verbalize"]:
        lines += render(name, probes[name])
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(probes)} probes, record {rec['id']})")


if __name__ == "__main__":
    main()
